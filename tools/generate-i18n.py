"""Generate the standalone Rust catalog from reviewed translation source rows."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MOD = ROOT
KEYS = ROOT / "translations/keys.json"


def main():
    rows = []
    for number in range(1, 5):
        rows.extend(json.loads((MOD / f"translations/part{number}.json").read_text(encoding="utf-8-sig")))
    expected = set(json.loads(KEYS.read_text(encoding="utf-8")))
    found = set()
    for row in rows:
        assert len(row) == 10 and all(isinstance(value, str) and value.strip() for value in row), row
        assert row[0] not in found, f"duplicate key {row[0]}"
        found.add(row[0])
        placeholders = set(re.findall(r"\{\d+\}", row[0]))
        for value in row[1:]:
            assert set(re.findall(r"\{\d+\}", value)) == placeholders, (row[0], value)
    assert found == expected, {"missing": sorted(expected - found), "extra": sorted(found - expected)}
    quote = lambda value: json.dumps(value, ensure_ascii=False)
    table = "\n".join("    (" + quote(row[0]) + ", [" + ", ".join(map(quote, row[1:])) + "])," for row in sorted(rows))
    code = '''// Generated by tools/generate-basic-hud-i18n.py; edit translations/part*.json.
// English source keys plus nine translated columns. No allocation in lookup.
pub const LANGUAGES: &[(&str, &str)] = &[
    ("auto", "Auto"), ("en_us", "English"), ("ru_ru", "Русский"),
    ("uk_ua", "Українська"), ("de_de", "Deutsch"), ("fr_fr", "Français"),
    ("es_es", "Español"), ("pt_br", "Português"), ("pl_pl", "Polski"),
    ("tr_tr", "Türkçe"), ("it_it", "Italiano"),
];

const ROWS: &[(&str, [&str; 9])] = &[
__TABLE__
];

fn column(language: &str) -> usize {
    let prefix = language.as_bytes().get(..2).unwrap_or_default();
    [b"ru", b"uk", b"de", b"fr", b"es", b"pt", b"pl", b"tr", b"it"]
        .iter().position(|code| prefix.eq_ignore_ascii_case(*code)).map_or(0, |i| i + 1)
}

pub fn tr<'a>(language: &str, key: &'a str) -> &'a str {
    let col = column(language);
    if col == 0 { return key; }
    ROWS.binary_search_by_key(&key, |(source, _)| *source)
        .map_or(key, |index| ROWS[index].1[col - 1])
}

pub fn fmt(language: &str, key: &str, args: &[&str]) -> String {
    let mut text = tr(language, key).to_owned();
    for (index, value) in args.iter().enumerate() {
        text = text.replace(&format!("{{{index}}}"), value);
    }
    text
}

pub fn language_name(code: &str) -> &'static str {
    LANGUAGES.iter().find(|(known, _)| code.eq_ignore_ascii_case(known)).map_or("Auto", |(_, name)| *name)
}

pub fn next_language(code: &str, delta: i32) -> &'static str {
    let current = LANGUAGES.iter().position(|(known, _)| code.eq_ignore_ascii_case(known)).unwrap_or(0);
    let next = (current as i64 + i64::from(delta)).rem_euclid(LANGUAGES.len() as i64) as usize;
    LANGUAGES[next].0
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rows_are_unique_sorted_and_complete() {
        assert!(ROWS.windows(2).all(|pair| pair[0].0 < pair[1].0));
        for (_, translations) in ROWS {
            assert!(translations.iter().all(|value| !value.trim().is_empty()));
        }
    }

    #[test]
    fn missing_keys_and_unknown_locales_keep_the_original() {
        assert_eq!(tr("xx", "Save"), "Save");
        assert_eq!(tr("ru_ru", "External player name"), "External player name");
    }
}
'''.replace("__TABLE__", table)
    target = MOD / "mixins/basic_hud/i18n.rs"
    target.write_text(code, encoding="utf-8")
    print(f"Generated {len(rows)} entries in ten languages: {target}")


if __name__ == "__main__":
    main()
